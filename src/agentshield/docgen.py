"""Generated reference docs (docs/SCENARIOS.md, docs/POLICIES.md). A test fails when they are stale."""

from __future__ import annotations

from collections import defaultdict

import yaml

from .policy import list_policies
from .sandbox.world import LIBRARY
from .scenarios import load_scenarios


def _taxonomy() -> dict:
    return yaml.safe_load((LIBRARY / "taxonomy.yaml").read_text(encoding="utf-8"))


def render_scenarios_md() -> str:
    tax = _taxonomy()
    cats = tax["categories"]
    by_cat: dict[str, dict[str, list]] = defaultdict(dict)
    for s in load_scenarios():
        by_cat[s.category].setdefault(s.id, []).append(s)
    ids = sum(len(v) for v in by_cat.values())
    cases = sum(len(x) for v in by_cat.values() for x in v.values())
    lines = [
        "# Scenario library",
        "",
        "<!-- generated by `agentshield docs`; do not edit by hand -->",
        "",
        f"{ids} scenario definitions expanding to {cases} executable cases, across {len(by_cat)} categories.",
        f"Risk IDs follow *{tax['llm']['edition']}* and *{tax['agentic']['edition']}*; review them against the current OWASP publications before using them for compliance mapping.",
        "",
    ]
    for cat in cats:
        if cat not in by_cat:
            continue
        lines += [f"## {cats[cat]}", "", "| Scenario | Agent | Severity | Variants | Risks | Checks |", "|---|---|---|---|---|---|"]
        for sid, group in by_cat[cat].items():
            s = group[0]
            checks = ", ".join(sorted({a.type for a in s.assertions}))
            variants = len(group) if s.variant else "-"
            lines.append(f"| `{sid}`<br>{s.name} | {s.target.agent} | {s.severity.value} | {variants} | {', '.join(s.owasp) or '-'} | {checks} |")
        lines.append("")
    return "\n".join(lines)


def render_policies_md() -> str:
    lines = ["# Policy sets", "", "<!-- generated by `agentshield docs`; do not edit by hand -->", ""]
    for p in list_policies():
        if p.id not in {"default", "strict", "permissive"}:
            continue
        lines += [f"## `{p.id}`", "", p.description, "", "| Rule | Tools | Severity | Effect | Risks |", "|---|---|---|---|---|"]
        for r in p.rules:
            lines.append(f"| `{r.id}`<br>{r.description} | {', '.join(r.tools)} | {r.severity.value} | {r.effect} | {', '.join(r.owasp) or '-'} |")
        lines.append("")
    return "\n".join(lines)
